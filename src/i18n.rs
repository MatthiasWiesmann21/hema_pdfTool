//! UI translations. Every language is one `const Tr`, so the compiler
//! guarantees that no string is missing. Placeholders like `{n}` are filled
//! in with [`fmt`].

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
pub enum Lang {
    #[default]
    De,
    En,
    Fr,
    Es,
    It,
}

impl Lang {
    pub const ALL: [Lang; 5] = [Lang::De, Lang::En, Lang::Fr, Lang::Es, Lang::It];

    pub fn native_name(self) -> &'static str {
        match self {
            Lang::De => "Deutsch",
            Lang::En => "English",
            Lang::Fr => "Français",
            Lang::Es => "Español",
            Lang::It => "Italiano",
        }
    }

    pub fn tr(self) -> &'static Tr {
        match self {
            Lang::De => &DE,
            Lang::En => &EN,
            Lang::Fr => &FR,
            Lang::Es => &ES,
            Lang::It => &IT,
        }
    }
}

/// Replaces `{key}` placeholders in `template`.
pub fn fmt(template: &str, args: &[(&str, &dyn std::fmt::Display)]) -> String {
    args.iter().fold(template.to_string(), |s, (k, v)| {
        s.replace(&format!("{{{k}}}"), &v.to_string())
    })
}

